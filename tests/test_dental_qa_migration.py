@pytest.mark.asyncio
async def test_evaluation_service_routes_dental_to_new_engine():
    eval_service = GeminiEvaluationService()

    fake_payload = {
        "overall_score": 92,
        "readiness_assessment": "Production Ready",
        "sop_audit_table": [],
    }

    with patch(
        "app.modules.dental_qa.service.DentalQAService.evaluate_transcript_payload",
        new=AsyncMock(return_value=(fake_payload, 92)),
    ) as mock_dental_eval:
        result_card, score = await eval_service.evaluate_chat_history(
            chat_history_str="User: Hello\nAssistant: Hi",
            scenario="dental_scheduling",
        )

        assert score == 92
        assert result_card["overall_score"] == 92
        mock_dental_eval.assert_called_once()


@pytest.mark.asyncio
async def test_evaluation_service_preserves_legacy_for_sbi():
    eval_service = GeminiEvaluationService()

    # When scenario is 'sbi', it should NOT call DentalQAService
    with patch(
        "app.modules.dental_qa.service.DentalQAService.evaluate_transcript_payload",
        new=AsyncMock(),
    ) as mock_dental_eval:
        with patch.object(
            eval_service, "_format_transcript", return_value="Sample transcript"
        ), patch("httpx.AsyncClient.post") as mock_post:
            mock_resp = MagicMock()
            mock_resp.status_code = 200
            mock_resp.json.return_value = {
                "candidates": [
                    {
                        "content": {
                            "parts": [
                                {
                                    "text": json.dumps({
                                        "overall_score": 85,
                                        "readiness_assessment": "Developing",
                                        "scenario_practiced": "SBI Motor Insurance",
                                    })
                                }
                            ]
                        }
                    }
                ]
            }
            mock_post.return_value = mock_resp

            result_card, score = await eval_service.evaluate_chat_history(
                chat_history_str="User: Hello",
                scenario="sbi",
            )

            # Dental QA Service must NOT have been called
            mock_dental_eval.assert_not_called()
            assert score == 85


