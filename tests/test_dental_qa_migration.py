# ──────────────────────────────────────────────────────────────
#  1. Transcript Formatting
# ──────────────────────────────────────────────────────────────

def test_dental_transcript_formatting():
    service = get_dental_qa_service()

    chat_payload = {
        "items": [
            {"role": "assistant", "text": "Hi, do you offer dental implants?"},
            {"role": "user", "text": "Can you give me a moment while I note down your details?"},
            {"role": "assistant", "text": "Sure, no problem."},
            {"role": "user", "text": "Our lead provider Dr. Mahima Gupta is one of the top implantologists in the country."},
        ]
    }

    transcript = service.format_transcript(json.dumps(chat_payload))
    assert "Patient: Hi, do you offer dental implants?" in transcript
    assert "Front Desk Trainee: Can you give me a moment while I note down your details?" in transcript
    assert "Patient: Sure, no problem." in transcript
    assert "Front Desk Trainee: Our lead provider Dr. Mahima Gupta" in transcript


