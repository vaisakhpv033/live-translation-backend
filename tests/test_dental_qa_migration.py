@pytest.mark.asyncio
async def test_report_service_dual_writes_for_dental():
    mock_repo = MagicMock(spec=IReportRepository)
    mock_repo.update_summary = AsyncMock()
    mock_repo.save_dental_evaluation = AsyncMock()

    dental_payload = {
        "overall_score": 88,
        "readiness_assessment": "Ready With Supervision",
        "sop_audit_table": [{"sop_id": "sop_balance_due"}],
    }

    mock_eval_service = MagicMock()
    mock_eval_service.evaluate_chat_history = AsyncMock(return_value=(dental_payload, 88))

    report_service = ReportService(repository=mock_repo, evaluation_service=mock_eval_service)

    await report_service.evaluate_and_update(
        job_id="job_dental_test_99",
        chat_history_str='{"items": []}',
        scenario="dental_scheduling",
    )

    # Must update reports table summary
    mock_repo.update_summary.assert_called_once()
    args, _ = mock_repo.update_summary.call_args
    assert args[0] == "job_dental_test_99"
    assert args[2] == 88  # overall_score
    assert args[3] == "completed"

    # Must dual-write to dental_evaluations table
    mock_repo.save_dental_evaluation.assert_called_once_with(
        "job_dental_test_99", dental_payload
    )

